"""Singleton loader for trained ML bundle and locked-Test benchmark metrics."""

import json
import os
from functools import lru_cache
from typing import Any

import joblib

from webapp.config import METRICS_PATH, MODEL_PATH, MODEL_SPECS


@lru_cache(maxsize=1)
def get_model_bundle() -> dict[str, Any]:
    """Load trained StandardScaler, PCA, and classifiers once per process."""
    if not os.path.exists(MODEL_PATH):
        raise FileNotFoundError(
            f"Không tìm thấy tệp mô hình tại {MODEL_PATH}. Vui lòng chạy `python -m src.pipeline` trước."
        )
    return joblib.load(MODEL_PATH)


@lru_cache(maxsize=1)
def get_metrics_summary() -> dict[str, Any]:
    """Load full experiment summary JSON generated by the training pipeline."""
    if not os.path.exists(METRICS_PATH):
        return {}
    with open(METRICS_PATH, "r", encoding="utf-8") as f:
        return json.load(f)


def get_per_class_map() -> dict[int, dict[str, Any]]:
    """Return ClassId -> test F1 / precision / recall lookup dict."""
    summary = get_metrics_summary()
    return {int(row["class_id"]): row for row in summary.get("per_class_knn_f5", [])}


def get_test_benchmarks() -> dict[str, dict[str, Any]]:
    """Return locked-Test Accuracy and Macro-F1 summaries keyed by model choice."""
    summary = get_metrics_summary()
    exp5 = summary.get("exp5_models_comparison", [])
    benchmarks: dict[str, dict[str, Any]] = {}
    for spec in MODEL_SPECS:
        row = next(
            (r for r in exp5 if r["model"].startswith(spec["metrics_prefix"])),
            None,
        )
        if row:
            benchmarks[spec["choice"]] = {
                "group_val_acc": round(row["group_val"]["accuracy"] * 100.0, 2),
                "test_acc": round(row["test"]["accuracy"] * 100.0, 2),
                "test_ci": round(row["bootstrap_ci"]["accuracy_halfwidth"] * 100.0, 2),
                "macro_f1": round(row["test"]["f1_macro"] * 100.0, 2),
            }
    return benchmarks
